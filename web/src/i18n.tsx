const dictionaries: Record<Locale, Record<string, string>> = { en: {}, it, es };

type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (text: string, vars?: Vars) => string;
  formatDate: (value: string, options?: Intl.DateTimeFormatOptions) => string;
  formatDateTime: (value: string) => string;
  formatRelative: (value: string) => string;
};

const dateLocales: Record<Locale, string> = {
  en: "en-GB",
  it: "it-IT",
  es: "es-ES",
};

const I18nContext = createContext<I18nValue | null>(null);

function interpolate(text: string, vars?: Vars) {
  if (!vars) {
    return text;
  }
  return text.replace(/\{(\w+)\}/g, (_, key: string) => (key in vars ? String(vars[key]) : `{${key}}`));
}

export function I18nProvider({
  locale,
  setLocale,
  children,
}: {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  children: ReactNode;
}) {
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const t = useCallback(
    (text: string, vars?: Vars) => interpolate(dictionaries[locale][text] ?? text, vars),
    [locale],
  );

  const formatDate = useCallback(
    (value: string, options?: Intl.DateTimeFormatOptions) => {
      if (!value) {
        return "";
      }
      const date = new Date(value.length <= 10 ? `${value}T00:00:00` : value);
      if (Number.isNaN(date.getTime())) {
        return value;
      }
      return new Intl.DateTimeFormat(dateLocales[locale], {
        day: "2-digit",
        month: "short",
        year: "numeric",
        ...options,
      }).format(date);
    },
    [locale],
  );

  const formatDateTime = useCallback(
    (value: string) => {
      if (!value) {
        return "";
      }
      const date = new Date(value);
      if (Number.isNaN(date.getTime())) {
        return value;
      }
      return new Intl.DateTimeFormat(dateLocales[locale], {
        day: "2-digit",
        month: "short",
        year: "numeric",
        hour: "2-digit",
        minute: "2-digit",
      }).format(date);
    },
    [locale],
  );

  const formatRelative = useCallback(
    (value: string) => {
      if (!value) {
        return "";
      }
      const date = new Date(value);
      const diff = date.getTime() - Date.now();
      const minutes = Math.round(diff / 60000);
      const formatter = new Intl.RelativeTimeFormat(dateLocales[locale], { numeric: "auto" });
      if (Math.abs(minutes) < 1) {
        return t("just now");
      }
      if (Math.abs(minutes) < 60) {
        return formatter.format(minutes, "minute");
      }
      const hours = Math.round(minutes / 60);
      if (Math.abs(hours) < 24) {
        return formatter.format(hours, "hour");
      }
      const days = Math.round(hours / 24);
      if (Math.abs(days) < 14) {
        return formatter.format(days, "day");
      }
      return formatDate(value);
    },
    [locale, t, formatDate],
  );

  const value = useMemo<I18nValue>(
    () => ({ locale, setLocale, t, formatDate, formatDateTime, formatRelative }),
    [locale, setLocale, t, formatDate, formatDateTime, formatRelative],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return value;
}

export function roleLabel(role: string, t: (text: string) => string) {
  switch (role) {
    case "admin":
      return t("Admin role");
    case "manager":
      return t("Manager");
    case "member":
      return t("Member");
    case "guest":
      return t("Guest");
    default:
      return role;
  }
}
